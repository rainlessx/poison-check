class FstecMapper:
    """Маппер находок poison-check на УБИ-идентификаторы ФСТЭК России.

    Логика маппинга:
    1. Точное совпадение Issue.code с ключом UBI_MAPPINGS.
    2. Prefix-matching для динамических кодов CVEDetector (MLS-CVE-*, MLS-PATTERN-*).
    3. Fallback: пустой список + предупреждение в лог.
    """

    def map_issue(self, issue: Issue) -> list[str]:
        """Возвращает список УБИ-идентификаторов для данного Issue.

        Параметры:
            issue: Issue, полученный от любого детектора poison-check.

        Возвращает:
            Список идентификаторов вида ['УБИ.067', 'УБИ.068'].
            Пустой список если маппинг не найден (код новый или неизвестный).
        """
        # 1. Точное совпадение
        if issue.code in UBI_MAPPINGS:
            return list(UBI_MAPPINGS[issue.code])

        # 2. Prefix-matching для динамических кодов CVEDetector.
        #    Используем longest-first, чтобы более специфичный ключ
        #    (например, MLS-PATTERN-OS-SYSTEM) выиграл у более общего
        #    префикса (MLS-PATTERN-).
        for key in sorted(UBI_MAPPINGS, key=len, reverse=True):
            if issue.code.startswith(key):
                return list(UBI_MAPPINGS[key])

        logger.debug(
            "FstecMapper: нет маппинга для кода %r — УБИ не назначены",
            issue.code,
        )
        return []

    def map_result(self, result: ScanResult) -> dict[str, list[Issue]]:
        """Группирует все Issues из ScanResult по УБИ-идентификаторам.

        Параметры:
            result: Итоговый результат прогона сканирования.

        Возвращает:
            Словарь {УБИ-идентификатор: [Issue, ...]}.
            Каждый Issue может встречаться под несколькими ключами,
            если он маппируется на несколько УБИ.
            Issues без маппинга попадают под ключ '_unmapped'.
        """
        grouped: dict[str, list[Issue]] = defaultdict(list)

        for file_result in result.results_per_file.values():
            for issue in file_result.issues:
                ubi_ids = self.map_issue(issue)
                if ubi_ids:
                    for ubi_id in ubi_ids:
                        grouped[ubi_id].append(issue)
                else:
                    grouped["_unmapped"].append(issue)

        return dict(grouped)

    def get_ubi_description(self, ubi_id: str) -> str:
        """Возвращает описание УБИ-идентификатора на русском языке.

        Параметры:
            ubi_id: Идентификатор вида 'УБИ.067'.

        Возвращает:
            Текстовое описание или заглушку если идентификатор неизвестен.
        """
        return UBI_DESCRIPTIONS.get(
            ubi_id,
            f"Описание для {ubi_id} недоступно — обратитесь к bdu.fstec.ru",
        )

    def compliance_tag(self, ubi_id: str) -> str:
        """Формирует compliance-тег в формате 'fstec:ubi-NNN'.

        Параметры:
            ubi_id: Идентификатор вида 'УБИ.067'.

        Возвращает:
            Строка вида 'fstec:ubi-067'.
        """
        # УБИ.067 → fstec:ubi-067
        normalized = ubi_id.lower().replace("уби.", "ubi-")
        return f"fstec:{normalized}"
