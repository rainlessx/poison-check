class GostMapper:
    """Маппер находок poison-check на разделы ГОСТ Р 56939-2024.

    Логика маппинга:
    1. Точное совпадение Issue.code с ключом ISSUE_TO_GOST.
    2. Prefix-matching для динамических кодов CVEDetector (MLS-CVE-*, MLS-PATTERN-*).
    3. Fallback: пустой список + предупреждение в лог.
    """

    def map_issue(self, issue: Issue) -> list[str]:
        """Возвращает список разделов ГОСТ Р 56939-2024 для данного Issue.

        Параметры:
            issue: Issue, полученный от любого детектора poison-check.

        Возвращает:
            Список номеров разделов вида ['5.3', '6.1'].
            Пустой список если маппинг не найден.
        """
        # 1. Точное совпадение
        if issue.code in ISSUE_TO_GOST:
            return list(ISSUE_TO_GOST[issue.code])

        # 2. Prefix-matching для динамических кодов CVEDetector.
        #    Longest-first, чтобы конкретный паттерн выиграл у общего префикса.
        for key in sorted(ISSUE_TO_GOST, key=len, reverse=True):
            if issue.code.startswith(key):
                return list(ISSUE_TO_GOST[key])

        logger.debug(
            "GostMapper: нет маппинга ГОСТ для кода %r",
            issue.code,
        )
        return []

    def map_result(self, result: ScanResult) -> dict[str, list[Issue]]:
        """Группирует все Issues по разделам ГОСТ Р 56939-2024.

        Параметры:
            result: Итоговый результат прогона сканирования.

        Возвращает:
            Словарь {раздел_ГОСТ: [Issue, ...]}.
            Issues без маппинга попадают под ключ '_unmapped'.
        """
        from collections import defaultdict
        grouped: dict[str, list[Issue]] = defaultdict(list)

        for file_result in result.results_per_file.values():
            for issue in file_result.issues:
                gost_sections = self.map_issue(issue)
                if gost_sections:
                    for section in gost_sections:
                        grouped[section].append(issue)
                else:
                    grouped["_unmapped"].append(issue)

        return dict(grouped)

    def get_section_description(self, section: str) -> str:
        """Возвращает описание раздела ГОСТ Р 56939-2024.

        Параметры:
            section: Номер раздела вида '5.3'.

        Возвращает:
            Текстовое описание или заглушку если раздел неизвестен.
        """
        return GOST_56939_2024.get(
            section,
            f"Описание раздела {section} ГОСТ Р 56939-2024 недоступно",
        )

    def compliance_tag(self, section: str) -> str:
        """Формирует compliance-тег в формате 'gost:56939-2024:5.3'.

        Параметры:
            section: Номер раздела вида '5.3'.

        Возвращает:
            Строка вида 'gost:56939-2024:5.3'.
        """
        return f"gost:56939-2024:{section}"

    def format_reference(self, section: str) -> str:
        """Формирует человекочитаемую ссылку на раздел ГОСТ.

        Параметры:
            section: Номер раздела вида '5.3'.

        Возвращает:
            Строка вида 'ГОСТ Р 56939-2024 п.5.3'.
        """
        return f"ГОСТ Р 56939-2024 п.{section}"
